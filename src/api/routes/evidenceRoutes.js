const { Router } = require('express');
const { authenticated, admin } = require('../middlewares/auth');
const auth = require('../controllers/AuthController');
const users = require('../controllers/UserController');
const orders = require('../controllers/OrderController');
const router = Router();
router.post('/auth/login', auth.login);
router.get('/tracking/:invoice', orders.track);
router.get('/tracking/:invoice/photo', orders.publicPhoto);
router.use(authenticated);
router.get('/auth/me', auth.me);
router.post('/auth/logout', auth.logout);
router.get('/users', admin, users.list);
router.post('/users', admin, users.create);
router.put('/users/:id', admin, users.update);
router.get('/orders', orders.list);
router.post('/orders', orders.create);
router.get('/orders/:id', orders.get);
router.put('/orders/:id', orders.update);
router.post('/orders/:id/status', orders.status);
router.delete('/orders/:id', admin, orders.archive);
router.post('/orders/:id/restore', admin, orders.restore);
router.get('/orders/:id/evidence/:evidenceId', orders.photo);
module.exports = router;
